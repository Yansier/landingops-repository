import { beforeEach, describe, expect, it, vi } from 'vitest'
import { configureApi } from './api'
import { createCloudflareConnection, createDeploymentDryRun, createPrimaryDomain, createUser, disableUser, getTemplateConfigForm, grantPrimaryDomain, grantTemplate, listInstances, precheckBaota, precheckDomainDns, revokePrimaryDomainGrant, revokeTemplateGrant, saveBaotaConfig, transferOwner, updateCloudflareConnection, uploadTemplate, verifyBaota, verifyCloudflareConnection } from './resources'

const ok=(data:unknown)=>new Response(JSON.stringify({data,request_id:'req'}),{status:200,headers:{'Content-Type':'application/json'}})
describe('业务请求契约',()=>{
  const fetchMock=vi.fn()
  beforeEach(()=>{fetchMock.mockReset();vi.stubGlobal('fetch',fetchMock);configureApi({csrf:()=>'token',unauthorized:vi.fn()})})
  it('用户创建和停用严格使用现有接口',async()=>{
    fetchMock.mockResolvedValueOnce(ok({id:'u'})).mockResolvedValueOnce(ok(null))
    await createUser({email:'staff@example.test',display_name:'员工',role:'staff',team_id:'team',password:'long password 123'})
    await disableUser('01ARZ3NDEKTSV4RRFFQ69G5FAV')
    expect(fetchMock.mock.calls[0][0]).toBe('/api/v1/users')
    expect(JSON.parse(fetchMock.mock.calls[0][1].body)).toMatchObject({role:'staff',team_id:'team'})
    expect(fetchMock.mock.calls[1][0]).toContain('/users/01ARZ3NDEKTSV4RRFFQ69G5FAV')
    expect(JSON.parse(fetchMock.mock.calls[1][1].body)).toEqual({status:'disabled'})
  })
  it('负责人转交携带乐观锁版本',async()=>{
    fetchMock.mockResolvedValue(ok({version:8}))
    await transferOwner('01ARZ3NDEKTSV4RRFFQ69G5FAV',{to_user_id:'01ARZ3NDEKTSV4RRFFQ69G5FAA',expected_instance_version:7,reason:'轮班'})
    expect(JSON.parse(fetchMock.mock.calls[0][1].body)).toMatchObject({expected_instance_version:7,reason:'轮班'})
  })
  it('空数据库实例列表返回正式空数组',async()=>{fetchMock.mockResolvedValue(ok([]));await expect(listInstances()).resolves.toEqual([])})
  it('模板上传使用单文件 multipart 且授权接口格式固定',async()=>{
    fetchMock.mockResolvedValue(ok({template_version_id:'version'}))
    await uploadTemplate(new File(['zip'], 'template.zip', {type:'application/zip'}))
    const uploadInit=fetchMock.mock.calls[0][1] as RequestInit
    expect(uploadInit.body).toBeInstanceOf(FormData)
    expect((uploadInit.headers as Headers).has('Content-Type')).toBe(false)
    expect((uploadInit.headers as Headers).get('X-CSRF-Token')).toBe('token')
    fetchMock.mockImplementation(()=>Promise.resolve(ok(null)))
    await grantTemplate('01ARZ3NDEKTSV4RRFFQ69G5FAV','01ARZ3NDEKTSV4RRFFQ69G5FAA')
    await revokeTemplateGrant('01ARZ3NDEKTSV4RRFFQ69G5FAV','01ARZ3NDEKTSV4RRFFQ69G5FAA')
    expect(fetchMock.mock.calls[1][0]).toContain('/grants')
    expect(fetchMock.mock.calls[1][1].method).toBe('POST')
    expect(fetchMock.mock.calls[2][1].method).toBe('DELETE')
  })
  it('Cloudflare 与主域名接口不回传客户端推断状态',async()=>{
    fetchMock.mockImplementation(()=>Promise.resolve(ok({id:'resource'})))
    await createCloudflareConnection({label:'Account',account_external_id:'acct',api_token:'secret-token'})
    await updateCloudflareConnection('01ARZ3NDEKTSV4RRFFQ69G5FAV',{api_token:'rotated-token',expected_version:3})
    await createPrimaryDomain({zone_id:'01ARZ3NDEKTSV4RRFFQ69G5FAA',domain_name:'pages.example.com'})
    await grantPrimaryDomain('01ARZ3NDEKTSV4RRFFQ69G5FAV','01ARZ3NDEKTSV4RRFFQ69G5FAA')
    await revokePrimaryDomainGrant('01ARZ3NDEKTSV4RRFFQ69G5FAV','01ARZ3NDEKTSV4RRFFQ69G5FAA')
    expect(fetchMock.mock.calls[0][0]).toBe('/api/v1/cloudflare-connections')
    expect(JSON.parse(fetchMock.mock.calls[0][1].body)).not.toHaveProperty('status')
    expect(JSON.parse(fetchMock.mock.calls[1][1].body)).toEqual({api_token:'rotated-token',expected_version:3})
    expect(JSON.parse(fetchMock.mock.calls[2][1].body)).toEqual({zone_id:'01ARZ3NDEKTSV4RRFFQ69G5FAA',domain_name:'pages.example.com'})
    expect(fetchMock.mock.calls[3][0]).toContain('/primary-domains/')
    expect(fetchMock.mock.calls[4][1].method).toBe('DELETE')
  })
  it('只读验证与 DNS 预检查使用固定资源路由和版本',async()=>{
    fetchMock.mockImplementation(()=>Promise.resolve(ok({status:'success'})))
    await verifyCloudflareConnection('connection',{zone_id:'zone',expected_connection_version:4,expected_zone_version:2})
    await precheckDomainDns('domain','www.pages.example.com')
    expect(fetchMock.mock.calls[0][0]).toBe('/api/v1/cloudflare-connections/connection/verifications')
    expect(JSON.parse(fetchMock.mock.calls[0][1].body)).toEqual({zone_id:'zone',expected_connection_version:4,expected_zone_version:2})
    expect(fetchMock.mock.calls[1][0]).toBe('/api/v1/primary-domains/domain/dns-prechecks')
    expect(JSON.parse(fetchMock.mock.calls[1][1].body)).toEqual({hostname:'www.pages.example.com'})
  })
  it('宝塔配置、验证与预检查只使用固定只读路由',async()=>{
    fetchMock.mockImplementation(()=>Promise.resolve(ok({status:'success'})))
    await saveBaotaConfig({base_url:'https://panel.example.test:8888',api_key:'secret-key'})
    await verifyBaota(3)
    await precheckBaota('page.example.test')
    expect(fetchMock.mock.calls[0][0]).toBe('/api/v1/settings/baota')
    expect(fetchMock.mock.calls[0][1].method).toBe('PUT')
    expect(fetchMock.mock.calls[1][0]).toBe('/api/v1/settings/baota/verifications')
    expect(JSON.parse(fetchMock.mock.calls[1][1].body)).toEqual({expected_version:3})
    expect(fetchMock.mock.calls[2][0]).toBe('/api/v1/settings/baota/prechecks')
    expect(JSON.parse(fetchMock.mock.calls[2][1].body)).toEqual({hostname:'page.example.test'})
  })
  it('部署预演固定模板版本且不提交团队或推断状态',async()=>{
    fetchMock.mockImplementation(()=>Promise.resolve(ok({status:'needs_attention'})))
    await getTemplateConfigForm('version-id')
    await createDeploymentDryRun({template_version_id:'version-id',primary_domain_id:'domain-id',subdomain_prefix:'offer',config:{private_note:'private'}})
    expect(fetchMock.mock.calls[0][0]).toBe('/api/v1/template-versions/version-id/config-form')
    expect(fetchMock.mock.calls[1][0]).toBe('/api/v1/deployment-dry-runs')
    const body=JSON.parse(fetchMock.mock.calls[1][1].body)
    expect(body).toEqual({template_version_id:'version-id',primary_domain_id:'domain-id',subdomain_prefix:'offer',config:{private_note:'private'}})
    expect(body).not.toHaveProperty('team_id')
    expect(body).not.toHaveProperty('status')
  })
})
